"""
Box.asm Generator for Nand to Tetris Capstone Project
Student: Priyanshu Pandey (Roll No: 2501730051, K = 51)
Calculates dimensions and base addresses from Personal Number K,
and outputs Box.asm matching the two-pointer rowAddr/wordAddr design.
"""

import sys


def generate_box_asm(k: int = 51) -> str:
    """Generate Hack assembly source for drawing/clearing a 20-row box at row K."""
    start_row = k
    height = 20
    w_words = (k % 4) + 1
    width_px = 16 * w_words
    base_addr = 16384 + (32 * k)

    asm_lines = [
        "// ==================================================================",
        "// Capstone Project: Box.asm",
        "// Course: Nand to Tetris - I (ETCNTC301)",
        "// School of Engineering & Technology, K.R. Mangalam University",
        "//",
        "// Student Name            : Priyanshu Pandey",
        "// Roll Number             : 2501730051",
        f"// Personal Number K       : {k}",
        f"// Starting Row            : {start_row} (rows {start_row} to {start_row + height - 1})",
        f"// Box Height              : {height} rows",
        f"// Box Width               : {width_px} pixels ({w_words} 16-bit words/row)",
        f"// Screen Base Address     : SCREEN + 32 * {k} = 16384 + {32 * k} = {base_addr}",
        "// ==================================================================",
        "",
        f"// Main polling loop and box setup in Box.asm (K = {k})",
        "(MAIN_LOOP)",
        "    @KBD",
        "    D=M",
        "    @DRAW_BOX",
        "    D;JNE       // Draw box if any key is pressed",
        "    @CLEAR_BOX",
        "    0;JMP       // Clear box if no key is pressed",
        "",
        "(DRAW_BOX)",
        f"    @{base_addr}",
        "    D=A",
        "    @rowAddr",
        f"    M=D         // Start at row {start_row} (16384 + 32 * {k})",
        f"    @{height}",
        "    D=A",
        "    @rowCount",
        f"    M=D         // Repeat for {height} rows",
        "",
        "(DRAW_ROW_LOOP)",
        "    @rowCount",
        "    D=M",
        "    @MAIN_LOOP",
        "    D;JEQ       // Return to polling once all rows are drawn",
        "",
        "    @rowAddr",
        "    D=M",
        "    @wordAddr",
        "    M=D         // Reset wordAddr = rowAddr at the start of every row",
        "",
        f"    @{w_words}",
        "    D=A",
        "    @wordCount",
        f"    M=D         // {w_words} word(s) across ({width_px} pixels)",
        "",
        "(DRAW_WORD_LOOP)",
        "    @wordCount",
        "    D=M",
        "    @DRAW_NEXT_ROW",
        "    D;JEQ",
        "",
        "    @wordAddr",
        "    A=M",
        "    M=-1        // Turn 16 pixels black (-1)",
        "",
        "    @wordAddr",
        "    M=M+1       // Advance to next word in row",
        "    @wordCount",
        "    M=M-1",
        "    @DRAW_WORD_LOOP",
        "    0;JMP",
        "",
        "(DRAW_NEXT_ROW)",
        "    @32",
        "    D=A",
        "    @rowAddr",
        "    M=D+M       // Next row starts 32 words further down",
        "    @rowCount",
        "    M=M-1",
        "    @DRAW_ROW_LOOP",
        "    0;JMP",
        "",
        "(CLEAR_BOX)",
        f"    @{base_addr}",
        "    D=A",
        "    @rowAddr",
        f"    M=D         // Start at row {start_row} (16384 + 32 * {k})",
        f"    @{height}",
        "    D=A",
        "    @rowCount",
        f"    M=D         // Repeat for {height} rows",
        "",
        "(CLEAR_ROW_LOOP)",
        "    @rowCount",
        "    D=M",
        "    @MAIN_LOOP",
        "    D;JEQ       // Return to polling once all rows are cleared",
        "",
        "    @rowAddr",
        "    D=M",
        "    @wordAddr",
        "    M=D         // Reset wordAddr = rowAddr at the start of every row",
        "",
        f"    @{w_words}",
        "    D=A",
        "    @wordCount",
        f"    M=D         // {w_words} word(s) across ({width_px} pixels)",
        "",
        "(CLEAR_WORD_LOOP)",
        "    @wordCount",
        "    D=M",
        "    @CLEAR_NEXT_ROW",
        "    D;JEQ",
        "",
        "    @wordAddr",
        "    A=M",
        "    M=0         // Clear 16 pixels back to white (0)",
        "",
        "    @wordAddr",
        "    M=M+1       // Advance to next word in row",
        "    @wordCount",
        "    M=M-1",
        "    @CLEAR_WORD_LOOP",
        "    0;JMP",
        "",
        "(CLEAR_NEXT_ROW)",
        "    @32",
        "    D=A",
        "    @rowAddr",
        "    M=D+M       // Next row starts 32 words further down",
        "    @rowCount",
        "    M=M-1",
        "    @CLEAR_ROW_LOOP",
        "    0;JMP",
        "",
    ]
    return "\n".join(asm_lines)


if __name__ == '__main__':
    k_arg = int(sys.argv[1]) if len(sys.argv) > 1 else 51
    out_file = sys.argv[2] if len(sys.argv) > 2 else "Box.asm"
    content = generate_box_asm(k_arg)
    with open(out_file, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"Generated {out_file} for K = {k_arg}")
